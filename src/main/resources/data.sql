-- 미션 템플릿별 예상 소요 시간(분)
UPDATE mission_template
SET estimated_minutes = CASE action_type
    WHEN '미스트 리터치' THEN 3
    WHEN '핸드/바디 로션 덧바르기' THEN 1
    WHEN '블루라이트 필터 켜기' THEN 1
    WHEN '실내 습도 체크하기' THEN 2
    WHEN '얼굴 만지지 않기 리마인드' THEN 1
    WHEN '카페인 오후 섭취 자제 알림' THEN 1
    WHEN '취침 전 스트레칭' THEN 5
    WHEN '스크린 알림 끄기' THEN 1
    WHEN '5분 심호흡' THEN 5
    WHEN '짧은 산책' THEN 10
    WHEN '좋아하는 음악 3분 듣기' THEN 3
    WHEN '식사 알림 설정' THEN 1
    WHEN '건강 간식 제안' THEN 3
    ELSE estimated_minutes
END;

-- 미션 템플릿별 화면 표시 제목
UPDATE mission_template
SET display_title = CONCAT(
    CASE timing
        WHEN '지금' THEN '지금'
        WHEN '점심후' THEN '점심 후'
        WHEN '퇴근전' THEN '퇴근 전'
        ELSE timing
    END,
    ' ',
    CASE intensity
        WHEN '가벼운' THEN '가볍게'
        WHEN '집중' THEN '집중해서'
        ELSE intensity
    END,
    ' ',
    CASE action_type
        WHEN '카페인 오후 섭취 자제 알림' THEN '카페인 오후 섭취 자제하기'
        WHEN '5분 심호흡' THEN '5분 심호흡하기'
        WHEN '짧은 산책' THEN '짧은 산책하기'
        WHEN '식사 알림 설정' THEN '식사 알림 설정하기'
        WHEN '건강 간식 제안' THEN '건강 간식 챙기기'
        ELSE action_type
    END
);

